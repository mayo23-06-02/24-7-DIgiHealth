// Regenerates lib/db/schema.generated.ts from a Postgres that has migrations applied.
// Usage: DATABASE_URL=postgres://... node scripts/gen-db-schema.mjs
import pg from "pg";
import fs from "node:fs";

const url = process.env.DATABASE_URL;
if (!url) throw new Error("Set DATABASE_URL to a Postgres with supabase/migrations applied");
const client = new pg.Client({ connectionString: url });
await client.connect();
const { rows } = await client.query(`
  select table_name, column_name, data_type, udt_name, is_nullable
  from information_schema.columns
  where table_schema = 'public'
  order by table_name, ordinal_position`);
await client.end();

function kind(r) {
  if (r.data_type === "ARRAY") return `${kind({ data_type: "", udt_name: r.udt_name.replace(/^_/, "") })}[]`;
  switch (r.udt_name) {
    case "uuid": return "uuid";
    case "timestamptz": case "timestamp": return "timestamptz";
    case "date": return "date";
    case "bool": return "bool";
    case "int2": case "int4": case "int8": case "float4": case "float8": case "numeric": return "num";
    case "json": case "jsonb": return "json";
    default: return "text";
  }
}
const out = {};
for (const r of rows) (out[r.table_name] ??= {})[r.column_name] = kind(r);
const body = JSON.stringify(out, null, 1).replace(/"(\w+)":/g, "$1:");
fs.writeFileSync(
  new URL("../lib/db/schema.generated.ts", import.meta.url),
  `// GENERATED by scripts/gen-db-schema.mjs — do not edit.\nexport type ColKind = "uuid" | "text" | "timestamptz" | "date" | "bool" | "num" | "json" | \`\${string}[]\`;\nexport const DB_SCHEMA: Record<string, Record<string, ColKind>> = ${body};\n`,
);
console.log("tables:", Object.keys(out).length);
